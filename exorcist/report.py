from __future__ import annotations

import html
import json

from .probes import OWASP
from .runner import Report


def to_text(rep: Report) -> str:
    v = rep.vulnerable()
    lines = [f"target {rep.target} · seed {rep.seed} · repeat {rep.repeat} · {len(rep.results)} attempts · vulnerable {len(v)} · errors {len(rep.errors())}"]
    for r in rep.results:
        mark = "ERR " if r.error else ("FAIL" if r.vulnerable else "ok  ")
        extra = r.error or (f"{r.hits}/{r.attempts} {r.evidence}" if r.vulnerable else "")
        lines.append(f"  {mark} {r.owasp} {r.atlas:<14} {r.severity:<6} {r.probe}/{r.variant} {extra}".rstrip())
    by: dict[str, int] = {}
    for r in v:
        by.setdefault(r.owasp, 0)
        by[r.owasp] += 1
    if by:
        lines.append("OWASP LLM Top 10: " + ", ".join(f"{k} {OWASP.get(k, '')} ×{n}" for k, n in sorted(by.items())))
    else:
        lines.append("no probe succeeded (this is not proof of safety: see README, limits)")
    return "\n".join(lines)


def to_json(rep: Report) -> str:
    return json.dumps(rep.to_dict(), indent=2, ensure_ascii=False)


def to_markdown(rep: Report) -> str:
    out = [f"# exorcist: {rep.target}", "", f"seed {rep.seed}, прогонов на вариант {rep.repeat}. Уязвимо {len(rep.vulnerable())} из {len(rep.results)}.", "", "| | OWASP | ATLAS | тяжесть | проба | попаданий | доказательство |", "|---|---|---|---|---|---|---|"]
    for r in rep.results:
        mark = "ERR" if r.error else ("FAIL" if r.vulnerable else "ok")
        ev = (r.error or r.evidence).replace("|", "\\|")
        out.append(f"| {mark} | {r.owasp} | {r.atlas} | {r.severity} | {r.probe}/{r.variant} | {r.hits}/{r.attempts} | {ev} |")
    return "\n".join(out) + "\n"


def to_html(rep: Report) -> str:
    rows = []
    for r in rep.results:
        cls = "err" if r.error else ("bad" if r.vulnerable else "ok")
        mark = "ERR" if r.error else ("FAIL" if r.vulnerable else "ok")
        rows.append(f"<tr class={cls}><td>{mark}</td><td>{r.owasp}</td><td>{html.escape(r.atlas)}</td><td>{r.severity}</td><td>{html.escape(r.probe)}/{html.escape(r.variant)}</td><td>{r.hits}/{r.attempts}</td><td>{html.escape(r.error or r.evidence)}</td></tr>")
    return (
        "<!doctype html><meta charset=utf-8><title>exorcist</title>"
        "<style>body{background:#000;color:#e8e8e8;font:14px Menlo,monospace;margin:2em}td,th{padding:.3em .8em;text-align:left}"
        ".bad td:first-child{color:#b3000f;font-weight:700}.err td:first-child{color:#8a8a8a}table{border-collapse:collapse}tr{border-bottom:1px solid #2a2a2a}</style>"
        f"<h1>exorcist</h1><p>{html.escape(rep.target)} · vulnerable {len(rep.vulnerable())}/{len(rep.results)}</p>"
        "<table><tr><th></th><th>OWASP</th><th>ATLAS</th><th>severity</th><th>probe</th><th>hits</th><th>evidence</th></tr>" + "".join(rows) + "</table>"
    )


def _q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def to_promptfoo(probes_ctx_seed: int = 0) -> str:
    """Экспорт проб в конфиг promptfoo (promptfooconfig.yaml). Ограничение: здесь только проверки на вхождение канарейки,
    сложные детекторы (URL-картинки, длина) в экспорт не попадают."""
    from .probes import PROBES, Context

    ctx = Context.make(probes_ctx_seed)
    lines = ["# generated by exorcist; the file was not run through promptfoo (see exorcist README)", "description: exorcist probes", "prompts:", "  - '{{user}}'", "providers:", "  - id: openai:chat:REPLACE_ME", "    config:", "      systemPrompt: " + _q(ctx.system_prompt), "tests:"]
    for pr in PROBES:
        if pr.id not in ("direct_override", "indirect_injection", "system_prompt_leak", "secret_disclosure"):
            continue  # у остальных проб детектор не сводится к вхождению строки
        wanted = [ctx.marker] if pr.id in ("direct_override", "indirect_injection") else [ctx.secret, ctx.api_key]
        for att in pr.build(ctx):
            lines.append(f"  - description: {_q(f'{pr.owasp} {pr.id}/{att.variant}')}")
            lines.append("    vars:")
            lines.append(f"      user: {_q(att.messages[-1]['content'])}")
            lines.append("    assert:")
            for c in wanted:
                lines.append(f"      - type: not-contains\n        value: {_q(c)}")
    return "\n".join(lines) + "\n"
